#!/usr/bin/env bash
# Refresh deploy/aws/terraform/vendor from the registry module versions this
# stack was written against. Those versions lived on the module blocks until
# the sources were switched to ./vendor/* (commit 8ca978c).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="$ROOT/deploy/aws/terraform/vendor"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# directory  github repo          tag       commit
pins=(
  "vpc terraform-aws-vpc v5.21.0 7c1f791efd61f326ed6102d564d1a65d1eceedf0"
  "eks terraform-aws-eks v20.37.2 8a0efdbbc84180a26e0bacfd2b6fcfceac53b3b6"
  "rds terraform-aws-rds v6.12.0 22b02b391e1164cc1805e8f27eb4e3a5bd79bb95"
  "iam terraform-aws-iam v5.59.0 0792d7f2753c265e3d610a58348fa1c551cbe4b8"
)

mkdir -p "$DEST"

{
  echo "# Generated by scripts/vendor-terraform-modules.sh. Do not edit."
  echo "# directory	upstream repository	tag	commit"
} >"$DEST/PINS"

for spec in "${pins[@]}"; do
  read -r name repo tag sha <<<"$spec"
  src="$WORK/$name"
  git clone --depth 1 --branch "$tag" "https://github.com/terraform-aws-modules/${repo}.git" "$src"
  got="$(git -C "$src" rev-parse HEAD)"
  if [[ "$got" != "$sha" ]]; then
    echo "pin mismatch for ${name}: expected ${sha}, got ${got}" >&2
    exit 1
  fi

  # VCS and upstream CI metadata are not part of the module Terraform loads.
  # examples, tests, docs, and terragrunt wrappers are omitted so validate
  # does not depend on their extra registry module sources.
  rm -rf "$src/.git" "$src/.github" "$src/examples" "$src/tests" "$src/docs" "$src/wrappers"
  rm -rf "${DEST}/${name}"
  mv "$src" "${DEST}/${name}"
  printf '%s\tterraform-aws-modules/%s\t%s\t%s\n' "$name" "$repo" "$tag" "$sha" >>"$DEST/PINS"
done

echo "vendored modules into ${DEST}"
